package middleware

import (
	"net/http"
	"net/http/httptest"
	"testing"

	"github.com/go-park-mail-ru/2026_2_villain_go_sync_backend/internal/requestid"
)

func TestRequestID(t *testing.T) {
	tests := []struct {
		name       string
		incomingID string
	}{
		{
			name: "generate request id",
		},
		{
			name:       "ignore client request id",
			incomingID: "client-provided-id",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var contextID string

			next := http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				contextID = requestid.FromContext(r.Context())
				w.WriteHeader(http.StatusNoContent)
			})

			handler := RequestID(next)

			req := httptest.NewRequest(http.MethodGet, "/api/me", nil)
			if tt.incomingID != "" {
				req.Header.Set("X-Request-ID", tt.incomingID)
			}

			rec := httptest.NewRecorder()
			handler.ServeHTTP(rec, req)

			headerID := rec.Header().Get("X-Request-ID")

			if len(headerID) != 32 {
				t.Errorf("request id length = %d, want 32", len(headerID))
			}

			if contextID != headerID {
				t.Errorf("context id = %q, header id = %q", contextID, headerID)
			}

			if headerID == tt.incomingID {
				t.Error("request id must be generated by server")
			}

			if rec.Code != http.StatusNoContent {
				t.Errorf("status = %d, want 204", rec.Code)
			}
		})
	}
}

func TestRequestID_Unique(t *testing.T) {
	handler := RequestID(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusOK)
	}))

	ids := make(map[string]bool)

	for i := 0; i < 10; i++ {
		req := httptest.NewRequest(http.MethodGet, "/", nil)
		rec := httptest.NewRecorder()

		handler.ServeHTTP(rec, req)

		id := rec.Header().Get("X-Request-ID")

		if id == "" {
			t.Fatal("request id is empty")
		}

		if ids[id] {
			t.Fatalf("duplicate request id: %s", id)
		}

		ids[id] = true
	}
}
